// Turns src/content/ai-search/*.md (the finished, editor-approved copy) into
// src/content/ai-search/pages.generated.ts so the pages and the .md/llms routes
// can import the text with no file reads at runtime. Run: node scripts/build-ai-content.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const dir = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "content", "ai-search");
const files = readdirSync(dir).filter((f) => f.endsWith(".md")).sort();
const out = {};
for (const f of files) out[f.replace(/\.md$/, "")] = readFileSync(join(dir, f), "utf8");
writeFileSync(
  join(dir, "pages.generated.ts"),
  `// GENERATED by scripts/build-ai-content.mjs from the .md files beside it. Do not edit.\nexport const AI_SEARCH_SOURCES: Record<string, string> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(`wrote ${files.length} sources`);
